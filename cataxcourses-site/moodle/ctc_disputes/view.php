<?php
// Evidence packet / Stripe form answers for one dispute, loaded from the store and shown inside Moodle.
require_once(__DIR__ . '/../../config.php');
require_once(__DIR__ . '/lib.php');
require_login();
$context = context_system::instance();
require_capability('block/ctc_disputes:view', $context);
$dispute = required_param('dispute', PARAM_ALPHANUMEXT);
$view = optional_param('view', 'packet', PARAM_ALPHA) === 'form' ? 'form' : 'packet';

$PAGE->set_context($context);
$PAGE->set_url(new moodle_url('/blocks/ctc_disputes/view.php', ['dispute' => $dispute, 'view' => $view]));
$PAGE->set_pagelayout($view === 'packet' ? 'print' : 'standard');
$PAGE->set_title($view === 'packet' ? 'Dispute evidence' : 'Stripe form answers');

$res = block_ctc_disputes_wp('disputes/' . rawurlencode($dispute) . '/' . $view);
echo $OUTPUT->header();
echo html_writer::tag('style', '.ctc-noprint{display:none}@media print{.ctc-mdl-bar{display:none}}');
echo html_writer::div(
    html_writer::link(new moodle_url('/my/'), '← Dashboard') . ' · ' .
    html_writer::link(new moodle_url('/blocks/ctc_disputes/view.php', ['dispute' => $dispute, 'view' => 'packet']), get_string('packet', 'block_ctc_disputes')) . ' · ' .
    html_writer::link(new moodle_url('/blocks/ctc_disputes/view.php', ['dispute' => $dispute, 'view' => 'form']), get_string('form', 'block_ctc_disputes')) . ' · ' .
    html_writer::link('https://dashboard.stripe.com/disputes/' . $dispute, 'Open in Stripe', ['target' => '_blank']) .
    ($view === 'packet' ? ' · <button class="btn btn-primary btn-sm" onclick="window.print()">Print / Save as PDF</button>' : ''),
    'ctc-mdl-bar', ['style' => 'margin:12px 0 18px']);
// The HTML is generated by the store's own dispute code (trusted, escaped there).
echo $res && isset($res['html']) ? $res['html'] : $OUTPUT->notification(get_string('fetchfailed', 'block_ctc_disputes'));
echo $OUTPUT->footer();
