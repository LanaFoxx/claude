import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
import fs from 'fs';
const [S, sub, prov = '0'] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', proxy: { server: process.env.HTTPS_PROXY } });
const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 }, ignoreHTTPSErrors: true });
await ctx.addCookies(JSON.parse(fs.readFileSync(S + '/pw_cookies.json')).map(c => ({ ...c, domain: c.domain.replace(/^\./, ''), secure: true })));
const p = await ctx.newPage();
p.on('pageerror', e => console.log('ERR', e.message));
await p.goto(`https://taxcoursefinder.com/wp-admin/post.php?post=${sub}&action=edit`, { waitUntil: 'networkidle' });
console.log('title', await p.title());
await p.screenshot({ path: `${S}/shots/pf-review.png`, fullPage: true });
await p.selectOption('select[name=provider]', prov);
await Promise.all([p.waitForNavigation({ waitUntil: 'networkidle' }), p.click('button[name=tcfd_do_apply]')]);
console.log('url', p.url());
console.log('notice', (await p.locator('.notice-success').allInnerTexts()).join(' | '));
console.log('provider', await p.evaluate(() => { const o = document.querySelector('select[name=provider] option:checked'); return o && o.value + ' ' + o.textContent; }));
console.log('status', await p.locator('#tcfd_profile_meta').innerText());
await p.screenshot({ path: `${S}/shots/pf-applied.png`, fullPage: true });
await b.close();
