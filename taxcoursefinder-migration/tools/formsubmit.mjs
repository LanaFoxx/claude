import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
const S = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', proxy: { server: process.env.HTTPS_PROXY } });
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message));
const posts = []; p.on('request', r => { if (r.url().includes('admin-ajax') && r.method() === 'POST') posts.push(r.postData() ? r.postData().length : 0); });
const replies = []; p.on('response', async r => { if (r.url().includes('admin-ajax') && r.request().method() === 'POST') replies.push(r.status() + ' ' + (await r.text().catch(() => '')).slice(0, 160)); });
await p.goto('https://taxcoursefinder.com/provider-application/?nc=' + Date.now(), { waitUntil: 'networkidle' });
const f = 'form[data-tcf-listing-form]';
const fill = (n, v) => p.fill(`${f} [name="${n}"]`, v);
await fill('school_name', 'TCF Test School (delete me)'); await fill('website', 'https://example.com');
await fill('contact_name', 'Mike'); await fill('contact_email', 'mike@dreamwebdigital.com');
await p.check(`${f} [name=ce_offered]`); await fill('ce_price', '49.95'); await fill('ce_regular', '59.95'); await fill('ce_url', 'https://example.com/ctec-20-hour');
await p.check(`${f} [name="features[]"][value=online_course_available]`); await p.check(`${f} [name="features[]"][value=digital_book_available]`);
await p.selectOption(`${f} [name=reporting]`, '24h');
await fill('ce_coupon_code', 'TESTCODE'); await fill('ce_coupon_details', '10% off'); await fill('ce_coupon_expires', '2026-12-31'); await fill('ce_coupon_applies', 'Online package only, new students');
await p.setInputFiles(`${f} [name=logo]`, S + '/testfiles/logo.png'); await p.check(`${f} [name=logo_ok]`);
await p.check(`${f} [name=confirm]`);
await p.waitForTimeout(6000); // the form rejects submissions sent within 5 seconds of loading
await p.dblclick(`${f} [type=submit]`); await p.click(`${f} [type=submit]`).catch(() => {});
await p.waitForURL(/listing-verified/, { timeout: 30000 });
await p.waitForTimeout(2500);
console.log('url:', p.url());
console.log('POSTs sent:', posts.length, '| replies:', replies);
console.log('page:', (await p.locator('[data-tcf-receipt-state="ok"]').innerText()).replace(/\s+/g, ' '));
console.log('button href:', await p.locator('[data-tcf-receipt-state="ok"] a').getAttribute('href'));
console.log('page errors:', errs);
await p.screenshot({ path: S + '/shots/lv-ok.png' });
await b.close();
