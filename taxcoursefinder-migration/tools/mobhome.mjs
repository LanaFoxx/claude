import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
import fs from 'fs';
const S = process.argv[2], live = process.argv[3] === 'live';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', proxy: { server: process.env.HTTPS_PROXY } });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
if (!live) await ctx.route(u => u.href.includes('?pv='), r => r.fulfill({ status: 200, contentType: 'text/html; charset=utf-8', body: fs.readFileSync(`${S}/pv/home.html`, 'utf8') }));
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('https://taxcoursefinder.com/' + (live ? '?nc=' + Date.now() : '?pv=1'), { waitUntil: 'networkidle' });
await p.screenshot({ path: S + '/shots/mhome-hero.png' });
await p.getByText('60 Hour Qualifying Education', { exact: true }).click(); await p.waitForTimeout(400);
console.log('after 60h tap:', await p.evaluate(() => (document.body.innerText.match(/\d+ providers[^\n]*\n?[^\n]*/) || [''])[0].replace(/\s+/g, ' ')));
await p.screenshot({ path: S + '/shots/mhome-qe.png' });
await p.getByText('20 Hour Continuing Education', { exact: true }).click(); await p.waitForTimeout(300);
await p.click('[data-tcf-menu-toggle]'); await p.waitForTimeout(300);
const state = () => p.evaluate(() => [...document.querySelectorAll('.tcf-header .dd')].map(d => d.firstElementChild.textContent.trim() + ':' + (getComputedStyle(d.querySelector('.dd-menu')).display)));
console.log('menu closed groups:', await state());
await p.screenshot({ path: S + '/shots/mmenu-closed.png' });
await p.locator('.tcf-header .dd > div:first-child').filter({ hasText: 'Resources' }).click(); await p.waitForTimeout(300);
console.log('after tapping Resources:', await state());
await p.screenshot({ path: S + '/shots/mmenu-res.png' });
await p.locator('.tcf-header .dd > div:first-child').filter({ hasText: 'Resources' }).click(); await p.waitForTimeout(300);
console.log('after tapping again:', await state(), 'errors', errs, 'scrollW', await p.evaluate(() => document.documentElement.scrollWidth));
await b.close();
